/** Anteil der Zeilen, die ein System mit einer eigenen Komponente abdeckt. */
export const coverageOf = (key: SystemKey | 'fink') =>
	key === 'fink'
		? benchmark.filter((row) => row.coverage === 'kolibri' || row.coverage === 'fink').length
		: benchmark.filter((row) => row[key] !== null).length;
